    @Given("HMG Role Admin wants to create a new Member with the following attributes")
    public void
            theHMGRoleAdminWantsToCreateANewMemberForTheProjectHmgNoticeWithTheFollowingAttributes(
                    DocString request) {
        scenarioContext.setContext("requestContent", request.getContent());
    }

    @When("the HMG Role Admin creates a new Member")
    public void theHMGRoleAdminCreatesANewMember() throws Exception {
        createMember();
    }

    @Then("the Member is created successfully with response code {int}")
    public void theMemberIsCreatedSuccessfullyWithResponseCode(int expectedResponseCode) {
        assertThat(scenarioContext.getContext("responseCode")).isEqualTo(expectedResponseCode);
    }

    @And("return the created Member")
    public void returnTheCreatedMember(DocString expectedResponseBody) throws Exception {
        var expectedResponseMap =
                mapper.readValue(expectedResponseBody.getContent(), HashMap.class);
        var result = (Map) scenarioContext.getContext("results");

        assertThat(result.get("key")).isEqualTo(expectedResponseMap.get("key"));
        assertThat(result.get("name")).isEqualTo(expectedResponseMap.get("name"));
        assertThat(result.get("apiKey")).isEqualTo(expectedResponseMap.get("apiKey"));
    }

    @And("return the created Member with an auto generated UUID")
    public void returnTheCreatedMemberWithAutoGeneratedUUID(DocString expectedResponseBody)
            throws Exception {
        var expectedResponseMap =
                mapper.readValue(expectedResponseBody.getContent(), HashMap.class);
        var result = (Map) scenarioContext.getContext("results");

        assertThat(result.get("key")).isEqualTo(expectedResponseMap.get("key"));
        assertThat(result.get("name")).isEqualTo(expectedResponseMap.get("name"));
        assertTrue(
                result.get("apiKey")
                        .toString()
                        .matches(
                                "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"));
    }

