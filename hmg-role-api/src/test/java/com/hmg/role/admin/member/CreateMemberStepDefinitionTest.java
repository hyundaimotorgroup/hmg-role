    @Given("an existing Member as the following attributes")
    public void anExistingMemberAsTheFollowingAttributes(DocString request) throws Exception {
        scenarioContext.setContext("requestContent", request.getContent());
        createMember();
    }

    @When("the HMG Role Admin creates a new Member with an existing or duplicate key")
    public void theHMGRoleAdminCreatesANewMemberWithAnExistingOrDuplicateKey() {
        createMember();
    }

    @When("the HMG Role Admin creates a new Member with an existing or duplicate apiKey")
    public void theHMGRoleAdminCreatesANewMemberWithAnExistingOrDuplicateApiKey() {
        createMember();
    }

    private void createMember() {
        var apiKey = scenarioContext.getContext("apiKeyProjectAdmin");
        var projectKey = scenarioContext.getContext("projectKey");
        Response response =
                request()
                        .log()
                        .all()
                        .contentType(ContentType.JSON)
                        .body(scenarioContext.getContext("requestContent"))
                        .headers("X-HMG-ROLE-API-KEY", apiKey)
                        .post("/api/admin/v1/projects/{projectKey}/members", projectKey);
        scenarioContext.setContext("responseCode", response.statusCode());
        var result = response.thenReturn().as(HashMap.class);
        if (response.statusCode() == 201) {
            scenarioContext.setContext("apiKey", result.get("apiKey"));
        }
        scenarioContext.setContext("results", result);
    }

    public boolean initialMemberChecking(String apiKey, String key, String projectKey) {
        if (StringUtils.isBlank(key)) {
            return true;
        }
        getMemberByKey(key, apiKey, projectKey);
        if (!scenarioContext.getContext("responseCode").equals(200)) {
            return true;
        }
        Response response =
                request()
                        .log()
                        .all()
                        .contentType(ContentType.JSON)
                        .headers("X-HMG-ROLE-API-KEY", apiKey)
                        .delete(
                                "/api/admin/v1/projects/{projectKey}/members/{memberKey}",
                                projectKey,
                                key);
        return ((Integer) response.statusCode()).equals(204);
    }

    private void getMemberByKey(String key, String apiKey, String projectKey) {
        Response response =
                request()
                        .log()
                        .all()
                        .contentType(ContentType.JSON)
                        .headers("X-HMG-ROLE-API-KEY", apiKey)
                        .get(
                                "/api/admin/v1/projects/{projectKey}/members/{memberKey}",
                                projectKey,
                                key);
        scenarioContext.setContext("responseCode", response.statusCode());
        var result = response.thenReturn().as(HashMap.class);
        scenarioContext.setContext("results", result);
    }
